"""make_tables.py -- LaTeX tables of Section 4 from sim_A.json, sim_B.json and real_out/real_results.json."""
import json, os, sys
sim = {}
for f in ("sim_A.json", "sim_B.json"):
    r = json.load(open(f)); sim.update(r)
real = json.load(open(os.path.join(sys.argv[1] if len(sys.argv) > 1 else "real_out", "real_results.json")))
out = sys.argv[2] if len(sys.argv) > 2 else "tables"
os.makedirs(out, exist_ok=True)
P = [r"$\alpha$", r"$\beta_1$", r"$\beta_2$"]
f3 = lambda x: f"{x:.3f}"
f4 = lambda x: f"{x:.4f}"


def write(name, caption, label, align, header, rows):
    s = ("\\begin{table}[htbp]\n\\centering\\small\n\\caption{" + caption + "}\\label{" + label + "}\n"
         "\\begin{tabular}{" + align + "}\n\\hline\n" + header + " \\\\ \\hline\n" + "\n".join(rows) + "\n\\hline\n\\end{tabular}\n\\end{table}\n")
    open(os.path.join(out, name + ".tex"), "w").write(s)


# ---- simulation table 1: MLE, unrestricted vs restricted -----------------------------------
rows = []
for k in ("A", "B"):
    v = sim[k]
    for p in range(3):
        rows.append(" & ".join([k if p == 0 else "", P[p], f3(v["mle_u"]["bias"][p]), f3(v["mle_u"]["mse"][p]),
                                f3(v["mle_r"]["bias"][p]), f3(v["mle_r"]["mse"][p]),
                                f"{v['mle_dmse']['mean'][p]:+.3f} ({v['mle_dmse']['se'][p]:.3f})"]) + r" \\")
    rows[-1] += r" \hline"
write("tab_sim_mle", "Bias and MSE of the unrestricted and the order-restricted MLE (1000 replications); the last column is the mean paired difference "
      "in squared error, restricted minus unrestricted, with its standard error.", "tab:sim_mle", "ccccccc",
      "Setting & Par. & \\multicolumn{2}{c}{Unrestricted} & \\multicolumn{2}{c}{Restricted} & $\\Delta$MSE (SE) \\\\ \\cline{3-4}\\cline{5-6}\n & & Bias & MSE & Bias & MSE & ", rows)

# ---- simulation table 2: 95% intervals ------------------------------------------------------
rows = []
for lab, key in (("Approximate (ACI)", "aci"), ("Bootstrap-$p$", "boot"), ("HPD (Bayes)", "hpd")):
    cells = []
    for k in ("A", "B"):
        for p in range(3):
            cells.append(f"{sim[k][key]['cp'][p]:.3f} ({sim[k][key]['al'][p]:.2f})")
    rows.append(" & ".join([lab] + cells) + r" \\")
write("tab_sim_ci", "Coverage probability (average length in brackets) of the 95\\% interval estimators (1000 replications). "
      "The HPD intervals are computed from the joint BG prior.", "tab:sim_ci", "lcccccc",
      "Method & \\multicolumn{3}{c}{Setting A} & \\multicolumn{3}{c}{Setting B} \\\\ \\cline{2-4}\\cline{5-7}\n & $\\alpha$ & $\\beta_1$ & $\\beta_2$ & $\\alpha$ & $\\beta_1$ & $\\beta_2$", rows)

# ---- simulation table 3: Bayes, unrestricted vs restricted ----------------------------------
rows = []
for k in ("A", "B"):
    v = sim[k]
    for loss, ku, kr in (("SEL", "bayes_sel_u", "bayes_sel_r"), ("LINEX", "bayes_lx_u", "bayes_lx_r")):
        for p in range(3):
            rows.append(" & ".join([k if (p == 0 and loss == "SEL") else "", loss if p == 0 else "", P[p],
                                    f3(v[ku]["bias"][p]), f3(v[ku]["mse"][p]), f3(v[kr]["bias"][p]), f3(v[kr]["mse"][p])]) + r" \\")
    rows[-1] += r" \hline"
write("tab_sim_bayes", "Bias and MSE of the Bayes estimators (squared-error and LINEX loss with $c=1$) under the joint BG prior (unrestricted) "
      "and the OBG prior (restricted); 1000 replications.", "tab:sim_bayes", "cccccccc",
      "Setting & Loss & Par. & \\multicolumn{2}{c}{Unrestricted} & \\multicolumn{2}{c}{Restricted} \\\\ \\cline{4-5}\\cline{6-7}\n & & & Bias & MSE & Bias & MSE", rows)

# ---- simulation table 4: prior sensitivity --------------------------------------------------
rows = []
for k in ("A", "B"):
    for i, (pr, v) in enumerate(sim[k]["sens"].items()):
        a, b = pr.split(",")
        rows.append(" & ".join([k if i == 0 else "", f"Gamma({a}, {b})"] +
                               [f3(x) for p in range(3) for x in (v["bias"][p], v["mse"][p])]) + r" \\")
    rows[-1] += r" \hline"
write("tab_sim_prior", "Sensitivity of the unrestricted Bayes estimates (SEL) to the prior: the same Gamma$(a,b)$ prior is used independently for "
      "$\\alpha$, $\\beta_1$ and $\\beta_2$; 1000 replications.", "tab:sim_prior", "llcccccc",
      "Setting & Prior & \\multicolumn{2}{c}{$\\alpha$} & \\multicolumn{2}{c}{$\\beta_1$} & \\multicolumn{2}{c}{$\\beta_2$} \\\\ \\cline{3-4}\\cline{5-6}\\cline{7-8}\n & & Bias & MSE & Bias & MSE & Bias & MSE", rows)

# ---- real data ------------------------------------------------------------------------------
d = real["design"]
rows = [" & ".join([str(i + 1), f"{d['t'][i]:.5f}".rstrip("0"), f"{d['pop'][i]}", f"{int(d['R1'][i])}", f"{int(d['R2'][i])}"]) + r" \\"
        for i in range(d["J"])]
write("tab_real_data", f"Censored OLED sample generated by the BJGAPHC scheme with $m={d['m']}$, $R_i=0$, $\\mathcal{{T}}_1={d['T1']:.3f}$, "
      f"$\\mathcal{{T}}_2={d['T2']:.3f}$ (case II, $T^*=t_7={d['Tstar']:.4f}$). Population 1 is the 12.36 mA sample and population 2 the 9.64 mA sample; "
      "$R_{1i}$, $R_{2i}$ are the numbers of units withdrawn at the $i$-th failure.", "tab:real_data", "ccccc",
      "$i$ & $t_i$ (hours/1000) & Population & $R_{1i}$ & $R_{2i}$", rows)

m = real["mle"]; full = real["fit"]["full_mle"]
rows = []
for p in range(3):
    rows.append(" & ".join([P[p], f3(full[p]), f3(m["unrestricted"][p]), f"({m['aci'][p][0]:.3f}, {m['aci'][p][1]:.3f})",
                            f"({m['boot'][p][0]:.3f}, {m['boot'][p][1]:.3f})", f3(m["restricted"][p])]) + r" \\")
write("tab_real_mle", "Maximum likelihood estimates for the censored OLED data with 95\\% approximate and bootstrap-$p$ intervals; "
      "the second column gives the MLEs from the complete samples.", "tab:real_mle", "cccccc",
      "Par. & Complete data & MLE & 95\\% ACI & 95\\% Bootstrap-$p$ & Restricted MLE", rows)

b = real["bayes"]
rows = []
for p in range(3):
    rows.append(" & ".join([P[p], f3(b["unrestricted"]["mean"][p]), f"({b['unrestricted']['hpd'][p][0]:.3f}, {b['unrestricted']['hpd'][p][1]:.3f})",
                            f3(b["restricted"]["mean"][p]), f"({b['restricted']['hpd'][p][0]:.3f}, {b['restricted']['hpd'][p][1]:.3f})",
                            f3(b["unrestricted"]["linex1"][p])]) + r" \\")
write("tab_real_bayes", "Bayes estimates for the censored OLED data (hyper-parameters $0.1$): posterior mean (SEL) with 95\\% HPD interval under the joint BG prior "
      "and under the OBG prior, and the LINEX estimate ($c=1$) under the BG prior.", "tab:real_bayes", "cccccc",
      "Par. & \\multicolumn{2}{c}{Unrestricted (BG)} & \\multicolumn{2}{c}{Restricted (OBG)} & LINEX \\\\ \\cline{2-3}\\cline{4-5}\n & Mean & 95\\% HPD & Mean & 95\\% HPD & (unrestr.)", rows)

rows = []
for pr, v in real["sens"].items():
    a_, b_ = pr.split(",")
    rows.append(" & ".join([f"Gamma({a_}, {b_})"] + [f3(x) for x in v["mean"]] + [f3(v["post_order"])]) + r" \\")
rows.append(" & ".join(["MLE"] + [f3(x) for x in m["unrestricted"]] + ["--"]) + r" \\")
write("tab_real_prior", "Sensitivity of the unrestricted posterior means (SEL) for the OLED data to the prior: the same Gamma$(a,b)$ prior for "
      "$\\alpha$, $\\beta_1$, $\\beta_2$; the last column is the posterior probability of $\\beta_1\\le\\beta_2$.", "tab:real_prior", "lcccc",
      "Prior & $\\alpha$ & $\\beta_1$ & $\\beta_2$ & $P(\\beta_1\\le\\beta_2\\mid\\text{data})$", rows)
print("tables written to", out)

# ---- figure of Section 4.2 drawn in LaTeX (pgfplots) from the data stored in real_results.json ----
fd = real.get("fig")
if fd:
    def coords(pts):
        return " ".join(f"({x:.5g},{y:.5g})" for x, y in pts)
    panels = []
    panels.append("\\nextgroupplot[xlabel={$\\alpha$}, ylabel={profile log-likelihood}, ymax=0.3]\n"
                  f"\\addplot[black, thick] coordinates {{{coords(fd['profile'])}}};\n"
                  f"\\addplot[red, dashed] coordinates {{({fd['mle'][0]:.5g},-10) ({fd['mle'][0]:.5g},0)}};")
    for k, (nm, lab) in enumerate([("alpha", "$\\alpha$"), ("beta1", "$\\beta_1$"), ("beta2", "$\\beta_2$")]):
        e, dn = fd["hist"][nm]["edges"], fd["hist"][nm]["dens"]
        pts = [(e[i], dn[i]) for i in range(len(dn))] + [(e[-1], dn[-1])]
        top = max(dn) * 1.05
        panels.append(f"\\nextgroupplot[xlabel={{{lab}}}, ymin=0, ymax={top:.4g}]\n"
                      f"\\addplot[ybar interval, fill=gray!30, draw=gray] coordinates {{{coords(pts)}}};\n"
                      f"\\addplot[red, dashed] coordinates {{({fd['mle'][k]:.5g},0) ({fd['mle'][k]:.5g},{top:.4g})}};\n"
                      f"\\addplot[blue] coordinates {{({fd['mean'][k]:.5g},0) ({fd['mean'][k]:.5g},{top:.4g})}};")
    fig = ("\\begin{figure}[htbp]\n\\centering\n\\resizebox{\\textwidth}{!}{%\n\\begin{tikzpicture}\n"
           "\\begin{groupplot}[group style={group size=4 by 1, horizontal sep=1.5cm}, width=4.6cm, height=3.6cm,\n"
           " tick label style={font=\\scriptsize}, label style={font=\\small}, scaled ticks=false]\n"
           + "\n".join(panels) + "\n\\end{groupplot}\n\\end{tikzpicture}}\n"
           "\\caption{OLED data: profile log-likelihood of $\\alpha$ (left; the dashed line marks the MLE) and posterior histograms of $\\alpha$, $\\beta_1$ and $\\beta_2$ "
           "under the joint BG prior without restriction (dashed red line: MLE; solid blue line: posterior mean).}\\label{fig:real}\n\\end{figure}\n")
    open(os.path.join(out, "fig_real.tex"), "w").write(fig)
    print("figure written")
